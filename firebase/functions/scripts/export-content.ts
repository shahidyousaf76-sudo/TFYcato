// Writes the single source of truth (src/content) to every client that needs an offline copy:
//   shared/game-content.json                          — reference copy
//   unity-game/Assets/Resources/default_content.json  — bundled in the app so the game plays offline
//   admin-dashboard/lib/default-content.json          — admin previews and defaults
//   firebase/remoteconfig.template.json               — Remote Config defaults (deploy with `firebase deploy --only remoteconfig`)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { DEFAULT_CONTENT } from '../src/content';
import { levelTotals } from '../src/domain/levels';
import { DEFAULT_RUNTIME, JSON_KEYS, RuntimeConfig } from '../src/domain/remoteConfig';

const root = resolve(__dirname, '../../..');
const write = (rel: string, data: unknown) => {
  const path = resolve(root, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log('wrote', rel);
};

const content = { ...DEFAULT_CONTENT, levels: DEFAULT_CONTENT.levels.map(l => ({ ...l, totals: levelTotals(l) })) };
const runtime = DEFAULT_RUNTIME;

write('shared/game-content.json', content);
write('unity-game/Assets/Resources/default_content.json', content);
write('unity-game/Assets/Resources/default_runtime.json', runtime);
write('admin-dashboard/lib/default-content.json', content);
write('shared/default-runtime.json', runtime);

// Web prototype: a classic script so index.html also works when opened straight from disk (file://).
const webPath = resolve(root, 'web-prototype/content.js');
mkdirSync(dirname(webPath), { recursive: true });
writeFileSync(webPath, `// Generated by firebase/functions/scripts/export-content.ts — do not edit by hand.\nwindow.TFY_CONTENT = ${JSON.stringify(content)};\nwindow.TFY_RUNTIME = ${JSON.stringify(runtime)};\n`, 'utf8');
console.log('wrote web-prototype/content.js');

const parameters: Record<string, unknown> = {};
for (const [key, value] of Object.entries(runtime) as [keyof RuntimeConfig, unknown][]) {
  const isJson = JSON_KEYS.includes(key);
  parameters[key] = {
    defaultValue: { value: isJson ? JSON.stringify(value) : String(value) },
    valueType: isJson ? 'JSON' : typeof value === 'boolean' ? 'BOOLEAN' : typeof value === 'number' ? 'NUMBER' : 'STRING',
    description: 'TFY Cat Adventure — see README (Remote Config)',
  };
}
write('firebase/remoteconfig.template.json', { parameters });
